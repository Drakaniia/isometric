/**
 * export.ts: what a visitor (or the skill) takes away.
 *   toSvg  standalone SVG with the current style and colours baked in
 *   toTsx  a self-contained React component: inline SVG, CSS variables for
 *          colours, props for style tokens, size, weight and hover motion
 */
import type { Drawing } from './model.js';
import type { RenderOptions } from './render.js';
import { render } from './render.js';
import { STYLES, baseTokens } from './styles.js';
import { EVAL_SLOT_SOURCE } from './color.js';

export function toSvg(d: Drawing, opts: RenderOptions = {}): string {
  const r = render(d, { ...opts, colors: 'baked', id: opts.id || `iso-${d.id}` });
  return `<?xml version="1.0" encoding="UTF-8"?>\n${r.svg}\n`;
}

export const componentName = (id: string): string =>
  id.split(/[^a-zA-Z0-9]+/).filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join('') || 'Drawing';

const ATTR: Record<string, string> = {
  class: 'className',
  'fill-opacity': 'fillOpacity',
  'stroke-width': 'strokeWidth',
  'stroke-opacity': 'strokeOpacity',
  'text-anchor': 'textAnchor',
  'font-size': 'fontSize',
  'font-family': 'fontFamily',
  'font-weight': 'fontWeight',
  'letter-spacing': 'letterSpacing',
};

/** SVG markup to JSX markup (the renderer only emits a small attribute set). */
export function svgToJsx(markup: string): string {
  return markup
    .replace(/ ([a-z-]+)="([^"]*)"/g, (_, k: string, v: string) => {
      if (k === 'style') {
        const obj = v.split(';').filter(Boolean).map((decl) => {
          const [p, val] = decl.split(':');
          const key = p.trim().replace(/-([a-z])/g, (_m, c: string) => c.toUpperCase());
          return `${key}: ${JSON.stringify(val.trim())}`;
        });
        return ` style={{ ${obj.join(', ')} }}`;
      }
      if (/^var\(/.test(v)) return ` ${ATTR[k] || k}="${v}"`;
      return ` ${ATTR[k] || k}="${v}"`;
    })
    .replace(/<path([^>]*)\/>/g, '<path$1 />');
}

export interface TsxOptions extends RenderOptions {
  /** Frames sampled for the hover/loop motion (default 12). */
  frames?: number;
}

/** A self-contained TSX component. No package needed: paste and use. */
export function toTsx(d: Drawing, opts: TsxOptions = {}): string {
  const style = opts.style || 'two-tone';
  const theme = opts.theme || 'light';
  const name = componentName(d.id);
  const ID = 'ISOID';
  const base = baseTokens(style, theme, opts.tokens);
  const rest = render(d, { ...opts, colors: 'vars', id: ID, phase: undefined });
  const exprs: Record<string, string> = { ...rest.exprs };

  const moving = new Set((d.motion?.tracks || []).map((t) => t.group));
  const N = d.motion ? Math.max(4, opts.frames || 12) : 0;
  let staticBody = '';
  let framesBody = '';
  if (N) {
    // Each frame contains the complete depth-sorted picture. Moving assemblies
    // can cross static parts, so grouping only movers would break occlusion.
    const frames: string[] = [];
    for (let i = 0; i < N; i++) {
      const fr = render(d, { ...opts, colors: 'vars', id: ID, phase: i / N });
      Object.assign(exprs, fr.exprs);
      frames.push(`<g class="iso-f iso-f${i}">${fr.body}</g>`);
    }
    framesBody = frames.join('\n      ');
    staticBody = framesBody;
  } else {
    staticBody = rest.body;
  }

  const [vx, vy, vw, vh] = rest.viewBox;
  const dur = d.motion?.duration ?? 0;
  const st = STYLES[style];
  const css = [
    '#${id} path,#${id} circle{vector-effect:non-scaling-stroke;stroke-linejoin:round;stroke-linecap:round}',
    '#${id} .s{stroke-width:0.9px}#${id} .o{stroke-width:${weight}px}#${id} .d{stroke-width:${weight * 0.75}px}',
  ];
  if (N) {
    css.push(
      `#\${id} .iso-f{visibility:hidden}#\${id} .iso-f0{visibility:visible}`,
      `@keyframes \${id}-f{0%{visibility:visible}${(100 / N).toFixed(3)}%{visibility:hidden}100%{visibility:hidden}}`,
      `#\${id}[data-animate="loop"] .iso-f,#\${id}[data-animate="hover"]:hover .iso-f,#\${id}[data-animate="hover"]:focus-visible .iso-f{animation:\${id}-f ${dur}s step-end infinite}`,
      Array.from({ length: N }, (_, i) => `#\${id} .iso-f${i}{animation-delay:-${(dur - (dur * i) / N).toFixed(3)}s}`).join(''),
      `@media (prefers-reduced-motion: reduce){#\${id} .iso-f{animation:none!important}}`,
    );
  }

  const fixIds = (s: string) =>
    s.replace(new RegExp(`id="${ID}-t"`, 'g'), 'id={`${id}-t`}').replace(new RegExp(`id="${ID}-d"`, 'g'), 'id={`${id}-d`}');

  return `/**
 * ${d.name}: isometric drawing generated by the /isometric skill.
 * Style: ${st.label} (${theme}). Self-contained: no dependencies beyond React.
 *
 * Re-theme with the tokens prop (ink, face, plinth, accent, bg) or by
 * overriding any --iso-* CSS variable on the element.
 */
"use client";
import * as React from "react";

type Tokens = { ink?: string; face?: string; plinth?: string; accent?: string; bg?: string };

export interface ${name}Props extends Omit<React.SVGProps<SVGSVGElement>, "ref"> {
  /** Width in px (or any CSS length). Height follows the aspect ratio. Default: 100% of the container. */
  size?: number | string;
  /** Base colours. Every shade is derived from these. */
  tokens?: Tokens;
  /** Line weight in px at the displayed size. */
  weight?: number;
  /** Motion: play on hover, loop forever, or stay still. */
  animate?: "hover" | "loop" | false;
  /** Accessible name. */
  title?: string;
}

const BASE: Required<Tokens> = ${JSON.stringify(base, null, 2).replace(/\n/g, '\n')};

/** Every colour in the drawing, as an expression over the base tokens. */
const SLOTS: Record<string, string> = ${JSON.stringify(exprs, null, 2)};

${EVAL_SLOT_SOURCE}

export default function ${name}({ size, tokens, weight = ${opts.weight ?? 1}, animate = ${d.motion ? '"hover"' : 'false'}, title = ${JSON.stringify(d.name)}, style, ...rest }: ${name}Props) {
  const id = "iso" + React.useId().replace(/[^a-zA-Z0-9_-]/g, "");
  const base = { ...BASE, ...tokens } as Record<string, string>;
  const vars: Record<string, string> = {};
  for (const k in SLOTS) vars["--iso-" + k] = slot(SLOTS[k], base);
  const css = \`${css.join('')}\`;
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="${[vx, vy, vw, vh].map((v) => Math.round(v * 100) / 100).join(' ')}"
      id={id}
      role="img"
      aria-labelledby={\`\${id}-t \${id}-d\`}
      data-animate={animate || undefined}
      tabIndex={animate === "hover" ? 0 : undefined}
      width={size ?? "100%"}
      style={{ height: "auto", ...(vars as React.CSSProperties), ...style }}
      {...rest}
    >
      <title id={\`\${id}-t\`}>{title}</title>
      <desc id={\`\${id}-d\`}>${d.description.replace(/[{}<>]/g, '')}</desc>
      <style>{css}</style>
      <g dangerouslySetInnerHTML={{ __html: ${JSON.stringify(staticBody)} }} />
    </svg>
  );
}
`;
}
